"""Build Presentation/assets/data.js from local NarcoTrace outputs (aggregates only).

The output is gitignored: it carries served forecast squares and derived grids.
Run from the repo root: python3 Presentation/tools/build_data.py
"""
import csv, json, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "ml/data/real/public_sources"
GEN = ROOT / "web/public/generated"
OUT = ROOT / "Presentation/assets/data.js"

monthly = collections.Counter()
with open(SRC / "excise_enforcement_monthly.csv") as f:
    for r in csv.DictReader(f):
        monthly[r["period_start"][:7]] += int(r["ndps_cases"])
series = [{"m": m, "v": v, "src": "excise_district_statements"} for m, v in sorted(monthly.items())]
with open(SRC / "excise_statewide_monthly.csv") as f:
    for r in csv.DictReader(f):
        series.append({"m": r["period_start"][:7], "v": int(r["ndps_cases"]), "src": "assembly_answer"})
live = collections.Counter()
with open(SRC / "excise_live_months.csv") as f:
    for r in csv.DictReader(f):
        live[r["period_start"][:7]] += int(r["count"])
for m, v in sorted(live.items()):
    if m not in {s["m"] for s in series}:
        series.append({"m": m, "v": v, "src": "excise_homepage"})

access = json.loads((GEN / "recovery/access_map.json").read_text())
need = json.loads((GEN / "recovery/need_map.json").read_text())
grid = json.loads((GEN / "hotspots/grid_forecast.json").read_text())

step = access["meta"]["cell_degrees"]
cells = access["cells"]
lat0 = min(c[0] for c in cells); lon0 = min(c[1] for c in cells)
grades = need["grades"]
packed = []
for c, g in zip(cells, grades):
    packed += [round((c[0] - lat0) / step), round((c[1] - lon0) / step), round(c[3]), c[2], "-sehe".index(g) if g in "-seh" else 0]
# grade codes: 0 none, 1 some, 2 elevated, 3 high  (need_map: '-', 's', 'e', 'h')
packed2 = []
for i in range(0, len(packed), 5):
    g = grades[i // 5]
    packed2 += packed[i:i + 4] + [{"-": 0, "s": 1, "e": 2, "h": 3}.get(g, 0)]

centres = [[c["lat"], c["lon"], 1 if "vimukthi" in c.get("kind", "") or c.get("register_category") == "G" else 0] for c in access["centres"]]
flagged = [[c["lat"], c["lon"], c["rank"], round(c["expected_reports_28d"], 3)] for c in grid["cells"]]
top = [{"rank": c["rank"], "place": c["locality"], "district": c["district"], "expected": round(c["expected_reports_28d"], 2), "ever": c["reports_here_ever"]} for c in grid["cells"][:20]]

data = {
    "series": series,
    "districts": access["districts"],
    "need": {"meta": need["meta"], "districts": need["districts"], "places": [{k: p[k] for k in ("place", "place_ml", "district", "grade", "cases_a_year", "people", "mean_km")} for p in need["places"][:12]]},
    "grid": {"lat0": lat0, "lon0": lon0, "step": step, "cols": ["i", "j", "pop", "km", "grade"], "cells": packed2},
    "centres": centres,
    "flagged": flagged,
    "top": top,
    "cutoff": {"v3": grid["v3_cutoff"], "v1": grid["cutoff_check"]},
    "weekly": grid["weekly_located_reports"],
    "located_reports": grid["located_reports_used"],
    "geo": json.loads((ROOT / "frontend/public/geo/kerala-districts.geojson").read_text()),
}
OUT.write_text("// Generated by tools/build_data.py — local only, do not commit.\nwindow.NT = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(OUT, OUT.stat().st_size // 1024, "KB;", len(series), "months;", len(cells), "cells")
print("first/last:", series[0], series[-1])
